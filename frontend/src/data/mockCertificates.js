// Small helper so every seed row stays short and readable.
function seed(row) {
  return {
    tokenId: row.tokenId,
    owner: row.student.address,
    student: row.student.name,
    studentId: row.student.studentId,
    issuer: row.issuer,
    institution: row.institution,
    title: row.title,
    course: row.course,
    grade: row.grade,
    date: row.date,
    expiry: row.expiry || '',
    skills: row.skills,
    description: row.description,
    issuedAt: new Date(row.date + 'T10:30:00Z').getTime(),
    revoked: Boolean(row.revoked),
    revokedReason: row.revokedReason || '',
    cid: row.cid,
    tokenURI: 'ipfs://' + row.cid,
    txHash: row.txHash,
  }
}

